#!/bin/sh
# build-telnet-sd.sh - assemble ONLY the Telnet bootstrap card into
# output/sd_card_telnet/. Compile-free: it just lays out the sdcard/telnet/
# payload and bakes in the credentials/Wi-Fi you choose via env vars. Safe to
# run standalone (needs a POSIX shell + openssl or python3 for the password
# hash); prepare-telnet-sd.ps1 wraps it with interactive prompts, and
# build-sdcard.sh calls it as part of the full build.
#
#   SRC                 repo root            (default /src)
#   OUT                 output dir           (default /output)
#   TELNET_ROOT_PASSWORD  root password for Telnet (empty => passwordless)
#   WIFI_MODE           ap | sta             (default ap = factory AP)
#   WIFI_SSID           network to join (sta) / advertise (custom ap)
#   WIFI_PASS           Wi-Fi password
#   WIFI_SECURITY       wpa2 | open          (default wpa2)
#   WIFI_IP/NETMASK/GW  static address for sta (empty IP => DHCP)
#
# Credentials are written ONLY under output/ (git-ignored), never into the repo.
set -u
SRC=${SRC:-/src}
OUT=${OUT:-/output}
TELDIR="$SRC/sdcard/telnet"
STL="$OUT/sd_card_telnet"

[ -d "$TELDIR" ] || { echo "ERROR: $TELDIR not found (run from the repo / inside the builder)" >&2; exit 1; }

echo "### assembling telnet card -> $STL"
rm -rf "$STL"
for f in _ht_ap_mode.conf hostapd hack.sh README.md \
         custom/configs/hack.conf custom/configs/wifi.conf \
         custom/configs/hostapd.conf custom/scripts/telnet.sh \
         custom/scripts/wifi.sh custom/scripts/sounds.sh custom/scripts/ftp.sh; do
    s="$TELDIR/$f"; d="$STL/$f"
    mkdir -p "$(dirname "$d")"
    [ -f "$s" ] && sed 's/\r$//' "$s" > "$d"
done

# Optional FTP: flip FTP=0 -> FTP=1 (and set the port) in the card's hack.conf.
if [ "${FTP_ENABLE:-0}" = "1" ]; then
    H="$STL/custom/configs/hack.conf"
    sed -e 's/^FTP=0/FTP=1/' -e "s/^FTP_PORT=.*/FTP_PORT=${FTP_PORT:-21}/" "$H" > "$H.tmp" \
        && mv -f "$H.tmp" "$H"
    echo "telnet card: FTP ENABLED (port ${FTP_PORT:-21})"
else
    echo "telnet card: FTP disabled"
fi
# Binary asset (silent clip for the factory-prompt mute): copy verbatim, no sed.
if [ -f "$TELDIR/custom/audio/silent.mp3" ]; then
    mkdir -p "$STL/custom/audio"
    cp "$TELDIR/custom/audio/silent.mp3" "$STL/custom/audio/silent.mp3"
fi
chmod 755 "$STL/hostapd" "$STL/hack.sh" \
          "$STL/custom/scripts/telnet.sh" "$STL/custom/scripts/wifi.sh" \
          "$STL/custom/scripts/sounds.sh" "$STL/custom/scripts/ftp.sh" 2>/dev/null || true
mkdir -p "$STL/logs"; : > "$STL/logs/.keep"

# --- Wi-Fi config (output only) ---------------------------------------------
WIFI_MODE=${WIFI_MODE:-ap}
WIFI_SECURITY=${WIFI_SECURITY:-wpa2}
WIFI_NETMASK=${WIFI_NETMASK:-255.255.255.0}
{
    echo "# Generated by build-telnet-sd.sh - do not commit."
    echo "MODE=${WIFI_MODE}"
    echo "SSID=${WIFI_SSID:-}"
    echo "PASS=${WIFI_PASS:-}"
    echo "SECURITY=${WIFI_SECURITY}"
    echo "IP=${WIFI_IP:-}"
    echo "NETMASK=${WIFI_NETMASK}"
    echo "GW=${WIFI_GW:-}"
    echo "SETTLE=8"
} > "$STL/custom/configs/wifi.conf"
echo "telnet card: Wi-Fi MODE=${WIFI_MODE} SSID='${WIFI_SSID:-<factory>}'"

# Custom AP hostapd.conf only when AP + SSID given; else drop the template so
# wifi.sh keeps the factory AP.
if [ "$WIFI_MODE" = ap ] && [ -n "${WIFI_SSID:-}" ]; then
    sed -e "s/BOOTSTRAP_SSID/${WIFI_SSID}/" \
        -e "s/BOOTSTRAP_PASSPHRASE/${WIFI_PASS:-}/" \
        "$TELDIR/custom/configs/hostapd.conf" > "$STL/custom/configs/hostapd.conf"
    echo "telnet card: custom AP hostapd.conf written (best effort)"
else
    rm -f "$STL/custom/configs/hostapd.conf"
fi

# --- Telnet root password (output only) -------------------------------------
if [ -n "${TELNET_ROOT_PASSWORD:-}" ]; then
    H=$(TRP="$TELNET_ROOT_PASSWORD" python3 - <<'PY' 2>/dev/null
import crypt, os
print(crypt.crypt(os.environ["TRP"], crypt.mksalt(crypt.METHOD_MD5)))
PY
)
    [ -n "$H" ] || { command -v openssl >/dev/null 2>&1 && H=$(openssl passwd -1 "$TELNET_ROOT_PASSWORD"); }
    if [ -n "$H" ]; then
        printf 'root:%s:19000:0:99999:7:::\n' "$H" > "$STL/shadow"
        echo "telnet card: root password SET (login as root on port 24)"
    else
        echo "WARN: no crypt tool (python3/openssl) -> no shadow; Telnet stays passwordless" >&2
    fi
else
    echo "telnet card: no TELNET_ROOT_PASSWORD -> passwordless root shell on port 24"
fi

( cd "$STL" && find . -type f ! -name SHA256SUMS | LC_ALL=C sort | xargs sha256sum > SHA256SUMS )
echo; echo "=== sd_card_telnet tree ==="; ( cd "$OUT" && find sd_card_telnet | LC_ALL=C sort )
echo; echo "telnet bootstrap ready at output/sd_card_telnet"
