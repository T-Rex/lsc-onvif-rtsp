## Not tested (needs the physical camera)

- Execution on the real ARM926EJ-S CPU and the 4.4.192 kernel (syscall
  fallbacks, kernel user helpers).
- Interface \`wlan0\`, the real camera IP and DHCP changes (tests used the
  container interface through the same code path, \`ONVIF_IFACE\`).
- WS-Discovery multicast on the Wi-Fi LAN (tested on the Docker bridge,
  including multicast loopback; Wi-Fi multicast/IGMP behaviour of the
  camera and the access point is unknown).
- Coexistence with \`anyka_ipc\` (port conflicts on 8080/3702, memory use).
- BusyBox applets of the camera firmware used by the scripts (\`setsid\`,
  \`ip\`/\`ifconfig\`, \`df\`, ...), FAT32 mount options.
- Real ONVIF clients (ONVIF Device Manager, NVRs) and playback of the RTSP
  stream through ONVIF.
- RAM and \`/tmp\` usage on the camera.

## Known limitations

- Frame rate and bit rate of the anyka_ipc encoder are not verified, so the
  configuration uses \`framerate=0\` and \`bitrate=0\` ("unknown"). The ONVIF
  schema requires numbers in VideoEncoderConfiguration, so upstream reports its
  built-in defaults there (30 fps, 5000 kbit/s) and \`0\` as the VideoSource
  frame rate. These numbers are not measurements. See the deployment guide for
  how to measure and set them.
- AAC parameters (16 kHz, 50 kbit/s in AudioEncoderConfiguration) are fixed in
  upstream code and are not measured either; so are Quality (100), GovLength
  (40) and H264Profile (High) in the VideoEncoderConfiguration template.
- The Events service is advertised (ONVIF Profile S requires it) but offers no
  topics: PullPoint and WS-BaseNotification are reported as unsupported.
- DeviceIO is advertised with 1 video source, 1 audio source, 0 outputs/relays.
- \`SystemReboot\` is implemented upstream and reboots the camera. With
  authentication disabled any LAN client can call it.
- Authentication is WS-UsernameToken with PasswordDigest only (no HTTP Digest),
  without replay protection (the Created timestamp is not checked).
- ONVIF credentials do not protect RTSP; anyka_ipc's RTSP has its own (or no)
  access control.
- IPv4 only.
